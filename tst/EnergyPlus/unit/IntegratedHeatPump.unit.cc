    instance.CurMode = IHPOperationMode::SCWHMatchWH;
    EXPECT_EQ(IHP.MinSpedSCWH, GetLowSpeedNumIHP(*state, 1));

    instance.CurMode = IHPOperationMode::SpaceClgDedicatedWaterHtg;
